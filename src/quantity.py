"""Разбор количества ингредиентов (ЛР-6, рефакторинг по SRP).

Функция раньше жила в main.py (_parse_qty): транспортный слой FastAPI
сам занимался разбором строк с числами. Модуль выделен, чтобы
функцию можно было тестировать и переиспользовать без запуска приложения.
"""


def parse_quantity(value):
    """Пытается преобразовать строку в число.

    Возвращает кортеж ``(число_или_None, исходная_строка)``. Запятая
    считается десятичным разделителем: «50,5» -> 50.5.
    """
    if value is None:
        return None, ""
    s = str(value).strip()
    if not s:
        return None, ""
    s2 = s.replace(",", ".")
    try:
        return float(s2), s
    except ValueError:
        return None, s
